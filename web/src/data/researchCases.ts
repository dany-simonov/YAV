export type ResearchTone = 'positive' | 'warning' | 'negative' | 'neutral';

export type MetricVisual =
  | {
      type: 'dimensions';
      values: Array<{ value: string; label: string }>;
    }
  | {
      type: 'duration';
      from: number;
      to: number;
      fromLabel: string;
      toLabel: string;
      unit: string;
      delta: string;
    }
  | {
      type: 'contrast';
      left: { value: string; label: string };
      right: { value: string; label: string };
    };

